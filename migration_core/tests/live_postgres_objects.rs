#[test]
fn postgres_refusals_carry_reason_codes() {
    let Some(s)=Sandbox::new() else { return };
    let mut source=db(&s.source);
    source.batch_execute("CREATE TYPE mood AS ENUM('ok'); CREATE TABLE sample(id bigint GENERATED ALWAYS AS IDENTITY(INCREMENT 2), token text DEFAULT lower('X'), label mood, CONSTRAINT positive CHECK(id>0)); CREATE INDEX filtered ON sample(token) WHERE token IS NOT NULL; CREATE TABLE other(id bigint GENERATED BY DEFAULT AS IDENTITY(START 3))").unwrap();
    // A user-owned table in a different schema provides the cross-schema FK fixture.
    db(&s.target).batch_execute("CREATE TABLE parent(id int PRIMARY KEY)").unwrap();
    source.batch_execute(&format!("CREATE TABLE child(id int REFERENCES {}.parent(id)); CREATE MATERIALIZED VIEW mv AS SELECT 1 AS id",s.target.schema.as_deref().unwrap())).unwrap();
    let refused=response("dump.run",json!({"source":s.source,"output_dir":s.dir}));
    assert_eq!(refused["event"],"error","{refused:#}");
    assert_eq!(refused["bypassable"],false);
    assert_eq!(refused["reasons"],json!({
        "unsupported_default:sample:id":"identity_always_unsupported",
        "unsupported_default:sample:token":"default_expression_unsupported",
        "unsupported_default:other:id":"sequence_options_unsupported",
        "check_constraint:sample:positive":"check_constraint_unsupported",
        "custom_type:sample:label":"custom_type_unsupported",
        "unsupported_index:sample:filtered":"index_shape_unsupported",
        "cross_schema_fk:child:child_id_fkey":"cross_schema_fk_unsupported",
        "materialized_view:mv":"materialized_view_unsupported"
    }));
    assert!(!s.dir.join("_tunnelforge_dump.json").exists());
    source.batch_execute("DROP TABLE sample,other,child CASCADE; CREATE TABLE plain(id int)").unwrap();
    let refused=response("dump.run",json!({"source":s.source,"output_dir":s.dir}));
    assert_eq!(refused["bypassable"],true,"{refused:#}");
    assert_eq!(refused["reasons"],json!({"materialized_view:mv":"materialized_view_unsupported"}));
}

#[test]
fn postgres_security_rules_inheritance_and_comments_are_reported() {
    let Some(s)=Sandbox::new() else { return };
    let mut source=db(&s.source);
    for ddl in ["ALTER TABLE sample ENABLE ROW LEVEL SECURITY", "ALTER TABLE sample FORCE ROW LEVEL SECURITY", "CREATE POLICY readable ON sample USING(true)", "CREATE RULE no_delete AS ON DELETE TO sample DO INSTEAD NOTHING"] {
        source.batch_execute("CREATE TABLE sample(id int PRIMARY KEY); INSERT INTO sample VALUES(1)").unwrap();
        source.batch_execute(ddl).unwrap();
        let code=if ddl.contains("RULE") {"rule_unsupported"} else {"row_security_unsupported"};
        let id=if code=="rule_unsupported" {"rule:sample:no_delete"} else {"policy:sample"};
        let refused=response("dump.run",json!({"source":s.source,"output_dir":s.dir}));
        assert_eq!(refused["event"],"error","{refused:#}");
        assert_eq!(refused["bypassable"],true);
        assert_eq!(refused["reasons"][id],code);
        let bypassed=run("dump.run",json!({"source":s.source,"output_dir":s.dir,"allow_incomplete":true}));
        assert_eq!(bypassed["strict_export"],false);
        assert!(bypassed["manifest_warnings"].as_array().unwrap().iter().any(|warning|warning.as_str().unwrap().contains(id)));
        run("dump.import",json!({"target":s.target,"input_dir":s.dir,"mode":"replace"}));
        assert_eq!(db(&s.target).query_one("SELECT count(*) FROM pg_policy WHERE polrelid='sample'::regclass",&[]).unwrap().get::<_,i64>(0),0);
        source.batch_execute("DROP TABLE sample CASCADE").unwrap();
        std::fs::remove_dir_all(&s.dir).unwrap();
    }
    for ddl in ["CREATE TABLE sample(id int); CREATE TABLE child(extra text) INHERITS(sample)",
                "CREATE TABLE sample(id int) PARTITION BY RANGE(id); CREATE TABLE child PARTITION OF sample FOR VALUES FROM(0) TO(10)"] {
        source.batch_execute(ddl).unwrap();
        for table in ["sample","child"] {
            for allow in [false,true] {
                let refused=response("dump.run",json!({"source":s.source,"output_dir":s.dir,"tables":[table],"allow_incomplete":allow}));
                assert_eq!(refused["event"],"error","{refused:#}");
                assert_eq!(refused["bypassable"],false);
                assert_eq!(refused["reasons"][format!("table_inheritance:{table}")],"table_inheritance_unsupported");
            }
        }
        source.batch_execute("DROP TABLE sample,child CASCADE").unwrap();
    }
    source.batch_execute("CREATE TABLE sample(id int); COMMENT ON TABLE sample IS 'table'; COMMENT ON COLUMN sample.id IS 'column'").unwrap();
    let inspected=migration_core::inspect_live(&s.source).unwrap();
    assert!(inspected.unsupported_objects.iter().all(|id|!id.starts_with("comment:")));
    assert_eq!(inspected.object_reasons["comment:sample:id"],"comments_not_exported");
    let exported=s.dump();
    let warnings=exported["manifest_warnings"].as_array().unwrap();
    assert_eq!(warnings.len(),1);
    assert!(warnings[0].as_str().unwrap().contains("comments_not_exported: comment:sample, comment:sample:id"));
    run("dump.import",json!({"target":s.target,"input_dir":s.dir,"mode":"replace"}));
    assert!(db(&s.target).query_one("SELECT obj_description('sample'::regclass,'pg_class'),col_description('sample'::regclass,1)",&[]).unwrap().get::<_,Option<String>>(0).is_none());
    source.batch_execute("CREATE TABLE many_comments(id int)").unwrap();
    for index in 0..25 { source.batch_execute(&format!("ALTER TABLE many_comments ADD COLUMN c{index} int; COMMENT ON COLUMN many_comments.c{index} IS 'column'")).unwrap(); }
    let capped=run("dump.run",json!({"source":s.source,"output_dir":s.dir,"overwrite":true}));
    assert_eq!(capped["manifest_warnings"].as_array().unwrap().len(),1);
    assert!(capped["manifest_warnings"][0].as_str().unwrap().ends_with("(+7)"));
}

#[test]
fn pg_generated_columns_round_trip_replace() {
    let Some(s)=Sandbox::new() else { return };
    let mut source=db(&s.source);
    source.batch_execute("CREATE TABLE sample(id int PRIMARY KEY, a int NOT NULL, g int GENERATED ALWAYS AS(a*2) STORED NOT NULL, t text GENERATED ALWAYS AS ('it''s a\\'::text) STORED, v int GENERATED ALWAYS AS (a+3) VIRTUAL); CREATE INDEX generated_idx ON sample(g); INSERT INTO sample(id,a) VALUES(1,4),(2,8)").unwrap();
    let before=source.query("SELECT attname,to_jsonb(a)->>'attgenerated',pg_get_expr(d.adbin,d.adrelid) FROM pg_attribute a JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum WHERE a.attrelid='sample'::regclass ORDER BY attnum",&[]).unwrap().iter().map(|row|(row.get::<_,String>(0),row.get::<_,String>(1),row.get::<_,String>(2))).collect::<Vec<_>>();
    for format in ["jsonl","tsv"] {
        let exported=run("dump.run",json!({"source":s.source,"output_dir":s.dir,"data_format":format,"compression":"none"}));
        assert_eq!(exported["format_version"],6); assert_eq!(exported["strict_export"],true);
        let imported=run("dump.import",json!({"target":s.target,"input_dir":s.dir,"mode":"replace"}));
        assert!(imported["program_warnings"].as_array().unwrap().iter().any(|warning|warning["code"]=="generated_values_recomputed" && warning["name"]=="sample"));
        let mut target=db(&s.target);
        let after=target.query("SELECT attname,to_jsonb(a)->>'attgenerated',pg_get_expr(d.adbin,d.adrelid) FROM pg_attribute a JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum WHERE a.attrelid='sample'::regclass ORDER BY attnum",&[]).unwrap().iter().map(|row|(row.get::<_,String>(0),row.get::<_,String>(1),row.get::<_,String>(2))).collect::<Vec<_>>();
        assert_eq!(before,after);
        assert_eq!(target.query_one("SELECT g,v,t FROM sample WHERE id=1",&[]).unwrap().get::<_,i32>(0),8);
        assert_eq!(target.query_one("SELECT g,v,t FROM sample WHERE id=1",&[]).unwrap().get::<_,String>(2),"it's a\\");
        target.batch_execute("UPDATE sample SET a=9 WHERE id=1").unwrap();
        assert_eq!(target.query_one("SELECT g,v FROM sample WHERE id=1",&[]).unwrap().get::<_,i32>(0),18);
        assert_eq!(target.query_one("SELECT v FROM sample WHERE id=1",&[]).unwrap().get::<_,i32>(0),12);
        assert!(target.batch_execute("UPDATE sample SET a=NULL WHERE id=1").is_err());
        assert_eq!(target.query_one("SELECT count(*) FROM pg_indexes WHERE schemaname=current_schema() AND indexname='generated_idx'",&[]).unwrap().get::<_,i64>(0),1);
        std::fs::remove_dir_all(&s.dir).unwrap();
    }
}

#[test]
fn pg_security_on_quoted_table_names_is_not_silently_omitted() {
    let Some(s)=Sandbox::new() else { return };
    db(&s.source).batch_execute("CREATE TABLE \"orders:archive\"(id int); ALTER TABLE \"orders:archive\" ENABLE ROW LEVEL SECURITY; CREATE RULE no_delete AS ON DELETE TO \"orders:archive\" DO INSTEAD NOTHING; CREATE TABLE plain(id int)").unwrap();
    let refused=response("dump.run",json!({"source":s.source,"output_dir":s.dir,"tables":["orders:archive"]}));
    assert_eq!(refused["event"],"error","{refused:#}");
    assert_eq!(refused["reasons"],json!({"policy:orders:archive":"row_security_unsupported","rule:orders:archive:no_delete":"rule_unsupported"}));
    let bypassed=run("dump.run",json!({"source":s.source,"output_dir":s.dir,"tables":["orders:archive"],"allow_incomplete":true}));
    assert_eq!(bypassed["manifest_warnings"].as_array().unwrap().len(),2);
    std::fs::remove_dir_all(&s.dir).unwrap();
    let unrelated=run("dump.run",json!({"source":s.source,"output_dir":s.dir,"tables":["plain"]}));
    assert_eq!(unrelated["strict_export"],true);
}

