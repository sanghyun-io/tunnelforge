    db(&s.source).batch_execute("CREATE FUNCTION twice(int) RETURNS int LANGUAGE sql IMMUTABLE AS 'SELECT $1*2'; CREATE TABLE sample(a int,g int GENERATED ALWAYS AS(twice(a)) STORED)").unwrap();
