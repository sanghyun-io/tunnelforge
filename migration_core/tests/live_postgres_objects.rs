#[test]
fn pg_copy_rejects_generated_in_column_list() {
    let Some(s)=Sandbox::new() else { return };
    let mut source=db(&s.source);
    source.batch_execute("CREATE TABLE sample(id int,g int GENERATED ALWAYS AS(id+1) STORED)").unwrap();
    let err=match source.copy_in("COPY sample(id,g) FROM STDIN") { Err(err)=>err, Ok(_)=>panic!("COPY accepted a generated column") };
    assert!(err.as_db_error().unwrap().message().contains("generated column"));
}

